export function exitTicketForPlan(planId) {
  return EXIT_TICKET_QUESTIONS[Number(planId)] || EXIT_TICKET_QUESTIONS[1];
}

export function exitTicketSummary(answers = []) {
  return EXIT_TICKET_SKILLS.map(skill => {
    const rows = answers.filter(answer => answer.skill_code === skill.code);
    return {
      ...skill,
      score: rows.filter(answer => answer.correct).length,
      max_score: rows.length,
    };
  });
}
